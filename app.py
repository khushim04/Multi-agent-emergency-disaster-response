# --------------------------------------------------
# WEATHER DASHBOARD
# --------------------------------------------------

def display_weather(result):
    st.subheader(f"🌦️ Weather Report — {result['location']}")

    st.caption(
        f"Observation time: {result['observation_time']}"
    )

    st.markdown("### Current Weather Indicators")

    col1, col2, col3, col4 = st.columns(4)

    with col1:
        st.metric(
            label="🌡️ Temperature",
            value=f"{result['temperature_c']} °C",
        )

    with col2:
        st.metric(
            label="💧 Humidity",
            value=f"{result['humidity_percent']}%",
        )

    with col3:
        st.metric(
            label="🌧️ Recent Rainfall",
            value=f"{result['rainfall_mm']} mm",
        )

    with col4:
        st.metric(
            label="💨 Wind Speed",
            value=f"{result['wind_speed_kmh']} km/h",
        )

    st.caption(
        "Rainfall represents the recent rainfall estimate provided by "
        "the weather service. Values in Demo Mode are simulated."
    )


# --------------------------------------------------
# DISPLAY COMPLETE ANALYSIS
# --------------------------------------------------

def display_result(result):
    display_weather(result)

    # Risk assessment
    st.subheader("🚦 Risk Assessment")

    risk = result.get("risk_level", "UNKNOWN")

    risk_details = {
        "LOW": {
            "icon": "🟢",
            "label": "LOW",
            "description": (
                "No prototype scoring thresholds triggered."
            ),
        },
        "MEDIUM": {
            "icon": "🟠",
            "label": "MEDIUM",
            "description": (
                "Prototype thresholds indicate increased attention."
            ),
        },
        "HIGH": {
            "icon": "🔴",
            "label": "HIGH",
            "description": (
                "Prototype thresholds indicate elevated attention."
            ),
        },
    }

    details = risk_details.get(
        risk,
        {
            "icon": "⚪",
            "label": "UNKNOWN",
            "description": "Risk classification is unavailable.",
        },
    )

    col1, col2 = st.columns([1, 3])

    with col1:
        st.metric(
            label="Prototype Risk Level",
            value=f"{details['icon']} {details['label']}",
        )

    with col2:
        st.info(details["description"])

    st.caption(
        "Prototype assessment only — not an official emergency warning."
    )

    st.markdown("### Recommended Action")
    st.write(
        result.get(
            "recommendation",
            "No recommendation available.",
        )
    )

    # Communication message
    st.subheader("📢 Communication Message")

    st.text(
        result.get(
            "communication_message",
            "No message generated.",
        )
    )

    # Shelter options
    st.subheader("🏠 Shelter Options")

    shelters = result.get("shelter_options", [])

    if shelters:
        for shelter in shelters:
            st.markdown(f"- {shelter}")

        st.caption(
            "Database records require independent verification "
            "of real-world status and current capacity."
        )
    else:
        st.info(
            "No matching shelter records found. Contact official "
            "emergency services for current shelter information."
        )

    # Agent activity logs
    with st.expander(
        "🤖 Agent Activity Logs",
        expanded=False,
    ):
        logs = result.get("agent_logs", [])

        if logs:
            for index, log in enumerate(logs, start=1):
                st.markdown(f"**Step {index}.** {log}")
        else:
            st.info("No agent activity logs are available.")

    # Final summary
    st.subheader("📋 Final Summary")

    st.write(
        result.get(
            "summary",
            "No summary generated.",
        )
    )


